/**
 * Foodie — enrichment SQL generator (batch-007 photos / batch-008 menus).
 *
 * Reads the reviewable worksheets produced by build-worksheets.ts and emits
 * the SAME style of fully-guarded transactional SQL the reviewed place-import
 * batches use (begin → preflight DO → guarded INSERTs → postflight DO → commit):
 *
 *   * idempotent  — every INSERT is WHERE NOT EXISTS on the natural key
 *                   (photos: restaurant_id + image_url; dishes: restaurant_id +
 *                   lower(btrim(name))); re-running inserts nothing.
 *   * preflight   — restaurant count drift guard (== 77), every referenced
 *                   restaurant id exists, required columns exist (with a
 *                   pointed "run migration-XXX first" message otherwise).
 *   * postflight  — inserted-set counts, per-set NULL-license check (photos),
 *                   NULL-source_url check (dishes), duplicate checks.
 *   * payload     — values preserved verbatim from the worksheet (names, URLs,
 *                   licenses, attributions, prices); deterministic ordering.
 *
 * ONLY approved_machine photo rows are ever emitted. Menu rows require a
 * recorded source URL. The generator never invents values.
 *
 * Determinism: same worksheets in → byte-identical SQL out. Never hand-edit
 * the generated files — change the worksheet/pipeline and regenerate.
 */

import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import type { MenuWorksheetRow, PhotoWorksheetRow } from "./lib/types";

/** Repo root — pipeline scripts are always run from the repo root (bun scripts/foodie-enrichment/…). */
const ROOT = process.cwd();
const HERE = join(ROOT, "scripts", "foodie-enrichment");
const WORKSHEETS = join(HERE, "worksheets");
const SUPABASE = join(HERE, "..", "..", "supabase");

const sq = (s: string): string => `'${s.replace(/'/g, "''")}'`;

interface PhotoWorksheetFile {
  generatedOn: string;
  counts: { candidates: number; approvedMachine: number; needsHumanReview: number; duplicatesSkipped: number };
  rows: PhotoWorksheetRow[];
}
interface MenuWorksheetFile {
  generatedOn: string;
  counts: { candidates: number; rows: number; droppedNoSource: number; placesWithItems: number };
  rows: MenuWorksheetRow[];
}

function generatePhotos(ws: PhotoWorksheetFile): string {
  const rows = ws.rows
    .filter((r) => r.verdict === "approved_machine" && !r.duplicateOf)
    .sort((a, b) => a.restaurantName.localeCompare(b.restaurantName) || a.imageUrl.localeCompare(b.imageUrl));
  const ids = [...new Set(rows.map((r) => r.restaurantId))].sort();
  const n = rows.length;

  const inserts = rows
    .map(
      (r) => `-- ${r.restaurantName} · ${r.sourceKind} · license ${r.license}
insert into public.restaurant_photos (restaurant_id, image_url, source_url, license, attribution)
select v.restaurant_id, v.image_url, v.source_url, v.license, v.attribution
from (values (
  ${sq(r.restaurantId)}::uuid,
  ${sq(r.imageUrl)},
  ${sq(r.sourceUrl)},
  ${sq(r.license)},
  ${sq(r.attribution)}
)) as v(restaurant_id, image_url, source_url, license, attribution)
where not exists (
  select 1 from public.restaurant_photos rp
  where rp.restaurant_id = ${sq(r.restaurantId)}::uuid
    and rp.image_url = ${sq(r.imageUrl)}
);`
    )
    .join("\n\n");

  const idValues = ids.length
    ? ids.map((id) => `  (${sq(id)}::uuid)`).join(",\n")
    : "  (null::uuid)"; // never matched — keeps the VALUES block valid when empty

  return `-- ============================================================================
-- Foodie — BATCH 007: restaurant photo enrichment (REV 1, generated)
-- ============================================================================
-- GENERATED by scripts/foodie-enrichment/gen-insert-batches.ts from
--   scripts/foodie-enrichment/worksheets/photo-enrichment.json
--   (worksheet generated ${ws.generatedOn}).
-- DO NOT HAND-EDIT. Re-run the pipeline to change; regenerate instead.
--
-- WHAT: ${n} machine-approved, license-recorded photo row(s) for ${ids.length} restaurant(s).
-- SOURCES: Wikimedia Commons / Openverse ONLY — every row carries a verbatim
--   license + attribution + source page recorded at research time. Candidates
--   whose usage rights could not be established were EXCLUDED by the pipeline
--   (${ws.counts.needsHumanReview} need human review, ${ws.counts.duplicatesSkipped} duplicate URL(s) skipped).
-- MATCH: each photo's source title contains the place's distinctive name
--   (matchKind "exact"); fuzzy/lead candidates never reach this file.
--
-- REQUIREMENTS / ORDER:
--   1. Run supabase/migration-006-photo-licensing.sql FIRST (this batch's
--      preflight verifies the licensing columns and refuses otherwise).
--   2. Paste this whole file into Supabase SQL Editor and run once.
--   3. IDEMPOTENT: safe to re-run — existing (restaurant_id, image_url)
--      pairs are skipped by the guard, so no duplicate photos can be created.
--
-- Transaction: any preflight/postflight failure rolls back EVERYTHING.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- Part 0 — preflight (drift + requirements). Any failure aborts the batch.
-- ---------------------------------------------------------------------------
do $$
declare
  total_rows integer;
  missing_ids text;
  has_license_cols boolean;
begin
  -- (a) the restaurants table is exactly the audited 77-row baseline
  select count(*) into total_rows from public.restaurants;
  if total_rows <> 77 then
    raise exception 'PREFLIGHT FAIL: restaurants table has % rows (expected 77). The live table drifted from the audited baseline — investigate before enriching.', total_rows;
  end if;

  -- (b) every photo target restaurant exists
  select string_agg(r.name, ', ') into missing_ids
  from (values
${idValues}
  ) as v(id)
  left join public.restaurants r on r.id = v.id
  where r.id is null;
  if missing_ids is not null then
    raise exception 'PREFLIGHT FAIL: target restaurant(s) not found in restaurants: %', missing_ids;
  end if;

  -- (c) migration-006 licensing columns must exist
  select bool_and(c."column" is not null) into has_license_cols
  from (values ('source_url'), ('license'), ('attribution')) as v("column")
  left join information_schema.columns c
    on c.table_schema = 'public'
   and c.table_name = 'restaurant_photos'
   and c.column_name = v."column";
  if has_license_cols is distinct from true then
    raise exception 'PREFLIGHT FAIL: restaurant_photos licensing columns missing — run supabase/migration-006-photo-licensing.sql first, then re-run this batch.';
  end if;

  raise notice 'PREFLIGHT OK: 77 restaurants, % target place(s), licensing columns present.', ${ids.length};
end $$;

-- ---------------------------------------------------------------------------
-- Part 1 — guarded photo inserts (idempotent on restaurant_id + image_url)
-- ---------------------------------------------------------------------------
${n === 0 ? `-- No machine-approved photo candidates this run — nothing to insert.\n-- (Keep the pipeline running: new license-approved matches will land here.)` : inserts}

-- ---------------------------------------------------------------------------
-- Part 2 — postflight. Verifies the inserted set; any failure rolls back.
-- ---------------------------------------------------------------------------
do $$
declare
  expected integer := ${n};
  found integer;
  null_licenses integer;
  dup_pairs integer;
begin
  -- (a) every expected (restaurant_id, image_url) pair exists exactly once
  select count(*) into found
  from (values
${rows.length ? rows.map((r) => `  (${sq(r.restaurantId)}::uuid, ${sq(r.imageUrl)})`).join(",\n") : "  (null::uuid, null::text)"}
  ) as v(restaurant_id, image_url)
  join public.restaurant_photos rp
    on rp.restaurant_id = v.restaurant_id
   and rp.image_url = v.image_url;
  if found <> expected then
    raise exception 'POSTFLIGHT FAIL: expected % photo row(s), found % — batch rolled back.', expected, found;
  end if;

  -- (b) licensing honesty: none of the inserted rows may have NULL license
  select count(*) into null_licenses
  from public.restaurant_photos rp
  where (rp.restaurant_id, rp.image_url) in (
${rows.length ? rows.map((r) => `    (${sq(r.restaurantId)}::uuid, ${sq(r.imageUrl)})`).join(",\n") : "    (null::uuid, null::text)"}
  ) and rp.license is null;
  if null_licenses <> 0 then
    raise exception 'POSTFLIGHT FAIL: % inserted photo row(s) have NULL license — usage rights must be recorded before display.', null_licenses;
  end if;

  -- (c) global duplicate guard on (restaurant_id, image_url)
  select count(*) into dup_pairs from (
    select restaurant_id, image_url
    from public.restaurant_photos
    group by restaurant_id, image_url
    having count(*) > 1
  ) d;
  if dup_pairs <> 0 then
    raise exception 'POSTFLIGHT FAIL: % duplicate (restaurant_id, image_url) pair(s) present.', dup_pairs;
  end if;

  raise notice 'POSTFLIGHT OK: % photo row(s) present with recorded licensing; no duplicates.', expected;
end $$;

commit;

-- Emergency manual rollback (only if ever needed):
--   begin;
--   delete from public.restaurant_photos rp
--   where (rp.restaurant_id, rp.image_url) in (
-- ${rows.length ? rows.map((r) => `     (${sq(r.restaurantId)}::uuid, ${sq(r.imageUrl)})`).join(",\n-- ") : "     (null::uuid, null::text)"}
--   );
--   commit;
`;
}

function generateMenus(ws: MenuWorksheetFile): string {
  const rows = [...ws.rows].sort(
    (a, b) =>
      a.restaurantName.localeCompare(b.restaurantName) ||
      a.name.localeCompare(b.name) ||
      (a.price ?? 0) - (b.price ?? 0)
  );
  const ids = [...new Set(rows.map((r) => r.restaurantId))].sort();
  const n = rows.length;

  const inserts = rows
    .map(
      (r) => `-- ${r.restaurantName} · ${r.name}${r.price != null ? ` · Rs ${r.price}` : " · (no published price)"}${r.isSignature ? " · signature" : ""}
insert into public.dishes (restaurant_id, name, price, is_signature, source_url)
select v.restaurant_id, v.name, v.price, v.is_signature, v.source_url
from (values (
  ${sq(r.restaurantId)}::uuid,
  ${sq(r.name)},
  ${r.price != null ? `${r.price}::numeric(10,2)` : "null::numeric(10,2)"},
  ${r.isSignature ? "true" : "false"},
  ${sq(r.sourceUrl)}
)) as v(restaurant_id, name, price, is_signature, source_url)
where not exists (
  select 1 from public.dishes d
  where d.restaurant_id = ${sq(r.restaurantId)}::uuid
    and lower(btrim(d.name)) = lower(btrim(${sq(r.name)}))
);`
    )
    .join("\n\n");

  const idValues = ids.length
    ? ids.map((id) => `  (${sq(id)}::uuid)`).join(",\n")
    : "  (null::uuid)";

  return `-- ============================================================================
-- Foodie — BATCH 008: menu / dish enrichment (REV 1, generated)
-- ============================================================================
-- GENERATED by scripts/foodie-enrichment/gen-insert-batches.ts from
--   scripts/foodie-enrichment/worksheets/menu-enrichment.json
--   (worksheet generated ${ws.generatedOn}).
-- DO NOT HAND-EDIT. Re-run the pipeline to change; regenerate instead.
--
-- WHAT: ${n} menu item(s) for ${ids.length} restaurant(s), EXACTLY as published by the
--   recorded source pages (round-3 reviewed worksheet notes + the places' own
--   recorded listing URLs). Prices appear ONLY where the source published one;
--   name-only items insert with price NULL. ${ws.counts.droppedNoSource} candidate(s) without any
--   recorded source URL were dropped by the pipeline (no provenance, no row).
--
-- REQUIREMENTS / ORDER:
--   1. Run supabase/migration-007-dish-provenance.sql FIRST (adds the nullable
--      dishes.source_url column; this batch's preflight verifies it).
--   2. Paste this whole file into Supabase SQL Editor and run once.
--   3. IDEMPOTENT: safe to re-run — existing (restaurant_id, dish name) pairs
--      are skipped, so duplicate menu items cannot be created.
--
-- Transaction: any preflight/postflight failure rolls back EVERYTHING.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- Part 0 — preflight (drift + requirements). Any failure aborts the batch.
-- ---------------------------------------------------------------------------
do $$
declare
  total_rows integer;
  missing_ids text;
  has_source_col boolean;
begin
  -- (a) the restaurants table is exactly the audited 77-row baseline
  select count(*) into total_rows from public.restaurants;
  if total_rows <> 77 then
    raise exception 'PREFLIGHT FAIL: restaurants table has % rows (expected 77). The live table drifted from the audited baseline — investigate before enriching.', total_rows;
  end if;

  -- (b) every menu target restaurant exists
  select string_agg(r.name, ', ') into missing_ids
  from (values
${idValues}
  ) as v(id)
  left join public.restaurants r on r.id = v.id
  where r.id is null;
  if missing_ids is not null then
    raise exception 'PREFLIGHT FAIL: target restaurant(s) not found in restaurants: %', missing_ids;
  end if;

  -- (c) migration-007 provenance column must exist
  select c.column_name is not null into has_source_col
  from information_schema.columns c
  where c.table_schema = 'public'
    and c.table_name = 'dishes'
    and c.column_name = 'source_url';
  if has_source_col is distinct from true then
    raise exception 'PREFLIGHT FAIL: dishes.source_url column missing — run supabase/migration-007-dish-provenance.sql first, then re-run this batch.';
  end if;

  raise notice 'PREFLIGHT OK: 77 restaurants, % target place(s), dishes.source_url present.', ${ids.length};
end $$;

-- ---------------------------------------------------------------------------
-- Part 1 — guarded dish inserts (idempotent on restaurant_id + item name)
-- ---------------------------------------------------------------------------
${n === 0 ? `-- No menu candidates this run — nothing to insert.\n-- (Keep the pipeline running: newly published menus will land here.)` : inserts}

-- ---------------------------------------------------------------------------
-- Part 2 — postflight. Verifies the inserted set; any failure rolls back.
-- ---------------------------------------------------------------------------
do $$
declare
  expected integer := ${n};
  found integer;
  null_sources integer;
  dup_names integer;
begin
  -- (a) every expected (restaurant_id, item name) pair exists exactly once
  select count(*) into found
  from (values
${rows.length ? rows.map((r) => `  (${sq(r.restaurantId)}::uuid, ${sq(r.name)})`).join(",\n") : "  (null::uuid, null::text)"}
  ) as v(restaurant_id, name)
  join public.dishes d
    on d.restaurant_id = v.restaurant_id
   and lower(btrim(d.name)) = lower(btrim(v.name));
  if found <> expected then
    raise exception 'POSTFLIGHT FAIL: expected % dish row(s), found % — batch rolled back.', expected, found;
  end if;

  -- (b) provenance honesty: every inserted item carries its source URL
  select count(*) into null_sources
  from public.dishes d
  where (d.restaurant_id, lower(btrim(d.name))) in (
${rows.length ? rows.map((r) => `    (${sq(r.restaurantId)}::uuid, lower(btrim(${sq(r.name)})))`).join(",\n") : "    (null::uuid, null::text)"}
  ) and d.source_url is null;
  if null_sources <> 0 then
    raise exception 'POSTFLIGHT FAIL: % inserted dish row(s) have NULL source_url — provenance is mandatory.', null_sources;
  end if;

  -- (c) global duplicate guard on (restaurant_id, item name)
  select count(*) into dup_names from (
    select restaurant_id, lower(btrim(name)) as name_key
    from public.dishes
    group by restaurant_id, lower(btrim(name))
    having count(*) > 1
  ) d2;
  if dup_names <> 0 then
    raise exception 'POSTFLIGHT FAIL: % duplicate (restaurant_id, name) pair(s) present.', dup_names;
  end if;

  raise notice 'POSTFLIGHT OK: % dish row(s) present with recorded provenance; no duplicates.', expected;
end $$;

commit;

-- Emergency manual rollback (only if ever needed):
--   begin;
--   delete from public.dishes d
--   where (d.restaurant_id, lower(btrim(d.name))) in (
-- ${rows.length ? rows.map((r) => `     (${sq(r.restaurantId)}::uuid, lower(btrim(${sq(r.name)})))`).join(",\n-- ") : "     (null::uuid, null::text)"}
--   );
--   commit;
`;
}

function main() {
  const photoWs = JSON.parse(readFileSync(join(WORKSHEETS, "photo-enrichment.json"), "utf8")) as PhotoWorksheetFile;
  const menuWs = JSON.parse(readFileSync(join(WORKSHEETS, "menu-enrichment.json"), "utf8")) as MenuWorksheetFile;

  const photosSql = generatePhotos(photoWs);
  const menusSql = generateMenus(menuWs);
  writeFileSync(join(SUPABASE, "insert-batch-007-photos.sql"), photosSql);
  writeFileSync(join(SUPABASE, "insert-batch-008-menus.sql"), menusSql);

  const photosCount = photoWs.rows.filter((r) => r.verdict === "approved_machine" && !r.duplicateOf).length;
  console.log(`[gen] supabase/insert-batch-007-photos.sql — ${photosCount} photo row(s)`);
  console.log(`[gen] supabase/insert-batch-008-menus.sql — ${menuWs.rows.length} menu item(s)`);
}

main();
